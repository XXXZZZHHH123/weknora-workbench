const assert = require('node:assert/strict');
const {generateReview, reviewControl, descendants, flush} = require('./judgment-manager-ui.cjs');
const catalogRequests = env => env.requests.filter(row => row.url.includes('/review/indicators'));
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  const env = await generateReview(), search = reviewControl(env, 'anchor', 'search');
  const list = descendants(env.nodes['logic-review-items']).find(node => node.id === search.attributes['aria-controls']);
  const menu = list.parentNode, more = reviewControl(env, 'anchor', 'more');
  await search.fire('focus');
  assert.equal(catalogRequests(env).length, 1); assert.equal(list.children.length, 2);
  const shown = list.children[1];
  await more.fire('click');
  assert.match(catalogRequests(env).at(-1).url, /offset=1/);
  assert.equal(list.children.length, 3, 'The next page is appended');
  assert.equal(list.children[1], shown, 'Rows already shown are kept, so a press on them is never lost to a rebuild');
  await search.fire('blur', {relatedTarget: more}); await wait(200);
  assert.equal(menu.hidden, false, 'Moving focus within the open list keeps it open');
  await search.fire('blur', {relatedTarget: null}); await wait(200);
  assert.equal(menu.hidden, true, 'Leaving the picker closes the list');
  await search.fire('focus');
  assert.equal(menu.hidden, false); assert.equal(catalogRequests(env).length, 2, 'Reopening the same query reuses loaded pages');
  assert.equal(list.children.length, 3);
  search.value = 'Directory'; await search.fire('input'); await wait(260); await flush();
  assert.equal(catalogRequests(env).length, 3, 'A new query searches again'); assert.match(catalogRequests(env).at(-1).url, /search=Directory/);
  menu.hidden = true; await search.fire('click');
  assert.equal(menu.hidden, false, 'Clicking a focused search box reopens its list');
  env.context.window.JudgmentManager.close();
  console.log('picker paging, focus and reuse checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
