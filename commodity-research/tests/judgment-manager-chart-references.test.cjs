const assert = require('node:assert/strict');
const {setup} = require('./judgment-manager-ui.cjs');
(async () => {
  const env = setup({chartMode:true,lifecycleMode:true});
  await env.context.window.JudgmentManager.open();
  assert.equal(env.nodes['logic-chart-editor'].hidden,false);
  assert.equal(env.nodes['logic-chart-target'].children.length,3);
  const target = {kind:'threshold',id:'risk'};
  env.nodes['logic-chart-target'].value=JSON.stringify(target);
  await env.nodes['logic-chart-insert'].fire('click');
  const mount=env.chartMounts.at(-1);
  assert.equal(mount.options.references.length,1);
  assert.equal(mount.options.references[0].id,'shared-chart');
  assert.deepEqual(JSON.parse(JSON.stringify(mount.options.references[0].target)),target);
  assert.equal(mount.options.asOf,'2024-03-01');
  assert.equal(mount.options.rules[0].series_id,'real-series');
  await env.nodes['logic-chart-save'].fire('click');
  const request=env.requests.find(row=>row.url.endsWith('/library-references'));
  assert.equal(request.body.judgment_id,42);
  assert.equal(request.body.base_version,2);
  assert.deepEqual(request.body.references,[{kind:'chart',id:'shared-chart',revision:3,target}]);
  assert.equal(new URL(env.navigations[0]).searchParams.get('judgment_id'),'44');
  assert.equal(env.requests.filter(row=>row.url.endsWith('/jobs')).length,0);
  env.nodes['logic-version'].value='record:43';
  await env.nodes['logic-version'].fire('change');
  const historic=env.chartMounts.at(-1);
  assert.equal(historic.container,env.nodes['logic-history-charts']);
  assert.equal(historic.options.references[0].id,'historical-chart');
  assert.equal(historic.options.asOf,'2024-02-01');
  env.context.window.JudgmentManager.close();
  const viewer=setup({chartMode:true,viewer:true});await viewer.context.window.JudgmentManager.open();
  assert.equal(viewer.nodes['logic-chart-insert'].disabled,true);
  await viewer.nodes['logic-chart-insert'].fire('click');
  assert.equal(viewer.chartMounts.at(-1).options.references.length,0);
  viewer.context.window.JudgmentManager.close();
  console.log('judgment chart insertion, target pin, new version and historical render arguments passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
