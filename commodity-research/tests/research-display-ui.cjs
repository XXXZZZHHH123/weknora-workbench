const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const id = 'kb-' + 'c'.repeat(48), legacy = 'EXAMPLE.quantity.stock';
const names = {[id]: '库存 / ID123456 / 周 [SHFE.EXAMPLE.main.settle]', [legacy]: '社会库存'};
const context = {window: {}, document: {getElementById: () => ({textContent: JSON.stringify(names)})}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../src/tin/web/static/research-display.js'), 'utf8'), context);
const display = context.window.ResearchDisplay;
assert.equal(display.indicator(id), '库存 / 周');
assert.equal(display.text(id + '回落'), '库存 / 周回落');
assert.equal(display.text(legacy + '下降'), '社会库存下降');
assert.equal(display.indicator('missing-physical-id'), '指标名称待核对');
assert.equal(display.text('价格 [SHFE.EXAMPLE.main.settle]'), '价格');
assert.equal(display.text('跟踪合约 AB2601'), '跟踪合约 AB2601');
const ref = {id: '42', revision: 23, title: '研判 v23', written_at: '2026-01-09'};
assert.equal(display.reference(ref), '研究判断 · 2026-01-09');
assert.equal(ref.id, '42'); assert.equal(ref.revision, 23);
assert.equal(display.reference({title: '已命名研判', created_at: '2026-01-09T10:24:00'}), '已命名研判 · 2026-01-09 10:24');
console.log('research-display UI checks passed');
